    date_key datetime primary key,
    Bank_Holiday_CY int,
    Bank_Holiday_UK int,
    CIGNA_Month_End int,
    cq_and_cy_name varchar(20),
    cq_name varchar(10),
    cy_name varchar(10),
    date_key_REAL datetime,
    day_cq_begin int,
    day_cq_end int,
    day_cy_begin int,
    day_cy_end int,
    day_fq_begin int,
    day_fq_end int,
    day_fy_begin int,
    day_fy_end int,
    day_month_begin int,
    day_month_end int,
    day_name datetime,
    day_number_in_cq int,
    day_number_in_cy int,
    day_number_in_fq int,
    day_number_in_fy int,
    day_number_in_month int,
    day_number_in_week int,
    day_number_til_end_cq int,
    day_number_til_end_fq int,
    fq_and_fy_name varchar(20),
    fq_name varchar(10),
    fy_name varchar(10),
    julian_counter int,
    month_and_cy_name varchar(8),
    month_and_fy_name varchar(8),
    month_name varchar(8),
    month_number int,
    month_number_in_cq int,
    month_number_in_cy int,
    month_number_in_fq int,
    month_number_in_fy int,
    month_number_til_end_cy int,
    month_number_til_end_fy int,
    vacation_day int,
    week_friday datetime,
    week_monday datetime,
    week_number int,
    week_number_cq int,
    week_number_cy int,
    week_number_fq int,
    week_number_fy int,
    week_number_til_end_cq int,
    week_number_til_end_cy int,
    week_number_til_end_fq int,
    week_number_til_end_fy int,
    week_saturday datetime,
    week_sunday datetime,
    weekdays varchar(3),
    Weekend_Working_Day_CY int,
    Working_Day_Counter_CY int,
    Working_Day_Counter_UK int,
    Working_Day_CY int,
    Working_Day_UK int
);
WITH DateSeries AS (
    SELECT CAST('2000-01-01' AS datetime) AS date_key
    UNION ALL
    SELECT date_key + 1
    FROM DateSeries
    WHERE date_key + 1 <= '2050-12-31'
)
