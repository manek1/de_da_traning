SELECT 
    date_key, 
    0 AS Bank_Holiday_CY,
    0 AS Bank_Holiday_UK,
    0 AS CIGNA_Month_End,
    'Q1 2022' AS cq_and_cy_name,
    'Q1' AS cq_name,
    '2022' AS cy_name,
    date_key AS date_key_REAL,
    1 AS day_cq_begin,
    0 AS day_cq_end,
    1 AS day_cy_begin,
    0 AS day_cy_end,
    1 AS day_fq_begin,
    0 AS day_fq_end,
    1 AS day_fy_begin,
    0 AS day_fy_end,
    1 AS day_month_begin,
    0 AS day_month_end,
    date_key AS day_name,
    DATEDIFF(DAY, '2022-01-01', date_key) + 1 AS day_number_in_cq,
    DATEDIFF(DAY, '2022-01-01', date_key) + 1 AS day_number_in_cy,
    DATEDIFF(DAY, '2022-01-01', date_key) + 1 AS day_number_in_fq,
    DATEDIFF(DAY, '2022-01-01', date_key) + 1 AS day_number_in_fy,
    DAY(date_key) AS day_number_in_month,
    DATEPART(WEEKDAY, date_key) AS day_number_in_week,
    90 - DATEDIFF(DAY, date_key, '2022-03-31') AS day_number_til_end_cq,
    90 - DATEDIFF(DAY, date_key, '2022-03-31') AS day_number_til_end_fq,
    'Q1 2022' AS fq_and_fy_name,
    'Q1' AS fq_name,
    '2022' AS fy_name,
    44196 AS julian_counter,
    FORMAT(date_key, 'MMM-yyyy') AS month_and_cy_name,
    FORMAT(date_key, 'MMM-yyyy') AS month_and_fy_name, -- Updated this part to correctly format it
    FORMAT(date_key, 'MMM') AS month_name,
    MONTH(date_key) AS month_number,
    DAY(date_key) AS month_number_in_cq,
    MONTH(date_key) AS month_number_in_cy,
    MONTH(date_key) AS month_number_in_fq,
    MONTH(date_key) AS month_number_in_fy,
    12 - MONTH(date_key) AS month_number_til_end_cy,
    12 - MONTH(date_key) AS month_number_til_end_fy,
    0 AS vacation_day,
    date_key - DAY(date_key) + 5 AS week_friday,
    date_key - DAY(date_key) + 1 AS week_monday,
    DATEPART(WEEK, date_key) AS week_number,
    DATEDIFF(WEEK, '2022-01-01', date_key) + 1 AS week_number_cq,
    DATEDIFF(WEEK, '2022-01-01', date_key) + 1 AS week_number_cy,
    DATEDIFF(WEEK, '2022-01-01', date_key) + 1 AS week_number_fq,
    DATEDIFF(WEEK, '2022-01-01', date_key) + 1 AS week_number_fy,
    53 - DATEDIFF(WEEK, date_key, '2022-12-31') AS week_number_til_end_cq,
    53 - DATEDIFF(WEEK, date_key, '2022-12-31') AS week_number_til_end_cy,
    53 - DATEDIFF(WEEK, date_key, '2022-12-31') AS week_number_til_end_fq,
    53 - DATEDIFF(WEEK, date_key, '2022-12-31') AS week_number_til_end_fy,
    date_key - DAY(date_key) + 6 AS week_saturday,
    date_key - DAY(date_key) AS week_sunday,
    CASE WHEN DATEPART(WEEKDAY, date_key) = 7 THEN 'Sat' ELSE 'Sun' END AS weekdays,
    0 AS Weekend_Working_Day_CY,
    31438 AS Working_Day_Counter_CY,
    31433 AS Working_Day_Counter_UK,
    0 AS Working_Day_CY,
    0 AS Working_Day_UK
FROM DateSeries
OPTION (MAXRECURSION 0);

